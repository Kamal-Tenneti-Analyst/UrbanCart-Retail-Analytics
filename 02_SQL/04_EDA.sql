
-- ==================================================================================================================
-- 01. Average Product Margin
-- ==================================================================================================================

SELECT
    AVG(
        (Selling_Price - Cost_Price)
        * 100.0
        / NULLIF(Selling_Price, 0)
    ) AS Average_Product_Margin_Percentage
FROM Products;

