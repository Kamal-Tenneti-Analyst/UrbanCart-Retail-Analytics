-- ==================================================================================================================
-- 02. Customer Overview
-- ==================================================================================================================

USE Urbancart_Retail;
GO

SELECT
    COUNT(*) AS Total_Customers,
    MIN(Join_Date) AS Earliest_Join_Date,
    MAX(Join_Date) AS Latest_Join_Date
FROM Customers;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 03. Customer Segments
-- ==================================================================================================================

SELECT
    Customer_Segment,
    COUNT(*) AS Customer_Count,
    COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER () AS Percentage_of_Customers
FROM Customers
GROUP BY Customer_Segment
ORDER BY Customer_Count DESC;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 04. Explore Order Status
-- ==================================================================================================================

SELECT
    Order_Status,
    COUNT(*) AS Order_Count,
    COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER () AS Percentage_of_Orders
FROM Orders
GROUP BY Order_Status
ORDER BY Order_Count DESC;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 05. Explore Payment Methods
-- ==================================================================================================================

SELECT
    Payment_Method,
    COUNT(*) AS Order_Count,
    COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER () AS Percentage_of_Orders
FROM Orders
GROUP BY Payment_Method
ORDER BY Order_Count DESC;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 06. Gender Distribution
