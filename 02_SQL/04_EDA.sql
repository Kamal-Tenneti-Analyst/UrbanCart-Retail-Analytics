-- ==================================================================================================================
-- 09. Order Overview
-- ==================================================================================================================

SELECT
    COUNT(*) AS Total_Orders,
    MIN(Order_Date) AS First_Order_Date,
    MAX(Order_Date) AS Last_Order_Date
FROM Orders;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 10. Overall AOV
-- ==================================================================================================================

SELECT
    SUM(od.Sales_Amount) /
        NULLIF(COUNT(DISTINCT o.Order_ID), 0) AS Average_Order_Value
FROM Orders o
JOIN Order_Details od
    ON o.Order_ID = od.Order_ID
WHERE o.Order_Status = 'Delivered';

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 11. Overall Revenue & Profit
-- ==================================================================================================================

SELECT
    SUM(Sales_Amount) AS Total_Revenue,
    SUM(Cost_Amount) AS Total_Cost,
    SUM(Profit_Amount) AS Total_Profit,
    SUM(Profit_Amount) * 100.0 /
        NULLIF(SUM(Sales_Amount), 0) AS Profit_Margin_Percentage
FROM Order_Details od
JOIN Orders o
    ON od.Order_ID = o.Order_ID
WHERE o.Order_Status = 'Delivered';

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 12. Product Category Distribution
-- ==================================================================================================================

SELECT
    Category,
    COUNT(*) AS Product_Count,
    AVG(Selling_Price) AS Average_Selling_Price
FROM Products
GROUP BY Category
ORDER BY Product_Count DESC;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 13. Product Overview
-- ==================================================================================================================

SELECT
    COUNT(*) AS Total_Products,
    COUNT(DISTINCT Category) AS Total_Categories,
    COUNT(DISTINCT Sub_Category) AS Total_Sub_Categories,
    COUNT(DISTINCT Brand) AS Total_Brands,
    MIN(Selling_Price) AS Minimum_Selling_Price,
    MAX(Selling_Price) AS Maximum_Selling_Price,
    AVG(Selling_Price) AS Average_Selling_Price
FROM Products;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 14. Product Price Analysis
-- ==================================================================================================================

SELECT
    MIN(Cost_Price) AS Minimum_Cost,
    MAX(Cost_Price) AS Maximum_Cost,
    AVG(Cost_Price) AS Average_Cost,
    MIN(Selling_Price) AS Minimum_Selling_Price,
    MAX(Selling_Price) AS Maximum_Selling_Price,
    AVG(Selling_Price) AS Average_Selling_Price
FROM Products;

----------------------------------------------------------------------------------------------------------------------------------------------------------------

-- ==================================================================================================================
-- 15. Transaction Overview
-- ==================================================================================================================

SELECT
    COUNT(*) AS Total_Order_Details,
    SUM(Quantity) AS Total_Units_Sold,
    AVG(Quantity * 1.0) AS Average_Units_Per_Line
FROM Order_Details;
